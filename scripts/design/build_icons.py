def inner(svg_text):
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg_text, re.S).group(1)
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    return " ".join(body.split()).replace(" />", "/>")

pkg, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
version = re.search(r'"version":\s*"([^"]+)"', (pkg / "package.json").read_text()).group(1)
icons = pkg / "icons"
lines = [
    '<svg xmlns="http://www.w3.org/2000/svg">',
    f"<!-- Glyphs from Lucide {version} (https://lucide.dev). ISC License, Copyright (c) Lucide Icons and Contributors. "
    "Glyphs derived from Feather: MIT License, Copyright (c) 2013-present Cole Bemis. Full texts: ICONS-LICENSE.txt next to this file. -->",
    "<!-- Generated by scripts/design/build_icons.py. Do not hand-edit. Stroke, caps and joins come from .icon in app.css. -->",
]
for sid, glyph, _ in GLYPHS:
    lines.append(f'<symbol id="i-{sid}" viewBox="0 0 24 24">{inner((icons / f"{glyph}.svg").read_text())}</symbol>')
lines.append("</svg>")
(out / "icons.svg").write_text("\n".join(lines) + "\n")

# The select arrow is a CSS background, which cannot follow currentColor, so it is drawn in --ink-2 at the 16 px stroke.
chevron = inner((icons / "chevron-down.svg").read_text())
(out / "select-chevron.svg").write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#4B4A46" stroke-width="2.25" '
    f'stroke-linecap="round" stroke-linejoin="round">{chevron}</svg>\n')
shutil.copyfile(pkg / "LICENSE", out / "ICONS-LICENSE.txt")
print(f"{len(GLYPHS)} symbols, {(out / 'icons.svg').stat().st_size} bytes -> {out / 'icons.svg'}")
